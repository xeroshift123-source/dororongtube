it('retains input focus across consecutive Enter submissions',async()=>{
  const now=vi.spyOn(Date,'now').mockReturnValue(10000)
  render(<ChatPanel messages={[]} nickname="test" userId="u" admin={false} status="connected" refresh={()=>{}}/>)
  const input=screen.getByRole('textbox',{name:'채팅 메시지'}) as HTMLTextAreaElement
  input.focus()
  fireEvent.change(input,{target:{value:'첫 번째'}})
  fireEvent.keyDown(input,{key:'Enter'})
  await vi.waitFor(()=>{expect(input.value).toBe('');expect(input.readOnly).toBe(false);expect(document.activeElement).toBe(input)})
  now.mockReturnValue(13001)
  fireEvent.change(input,{target:{value:'두 번째'}})
  fireEvent.keyDown(input,{key:'Enter'})
  await vi.waitFor(()=>expect(input.value).toBe(''))
  expect(rpc.mock.calls.map(call=>call[1].p_message)).toEqual(['첫 번째','두 번째'])
  expect(document.activeElement).toBe(input)
})
